    @Test fun plsqlBlocksAndProceduresRunFromAScript() = Session(fx.ds, fx.password).use { s ->
        val script = """
            create or replace procedure bump(p_n in number) as
            begin
              insert into auto(n) values (p_n);
              insert into auto(n) values (p_n + 1);
            end;
            /
            begin
              bump(40);
            end;
            /
            select count(*) from auto where n in (40, 41)
        """.trimIndent()
        DriverManager.getConnection(fx.ds.url, fx.ds.user, fx.password).use { it.createStatement().execute("delete from auto") }
        val parts = ksqlc.sql.splitStatements(script, slashBlocks = true).map { it.text(script) }
        assertEquals(3, parts.size, parts.toString())
        val results = s.runScript(parts)
        assertTrue(results.none { it is StatementResult.Failed }, results.toString())
        assertEquals(listOf<Any?>(java.math.BigDecimal(2)), (results.last() as StatementResult.Rows).cursor.fetch(1).single().map { it })
    }
