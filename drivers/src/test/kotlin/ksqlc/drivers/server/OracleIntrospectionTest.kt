    @Test fun ddlComesFromDbmsMetadataAndReplaysCleanly() = intro().use { i ->
        val ddl = i.ddl(obj("CUSTOMERS"))
        assertContains(ddl, "CREATE TABLE \"$owner\".\"CUSTOMERS\"")
        assertContains(ddl, "GENERATED ALWAYS AS IDENTITY")
        assertTrue("TABLESPACE" !in ddl && "STORAGE" !in ddl, "sin cláusulas de almacenamiento: $ddl")
        assertContains(ddl, "CREATE UNIQUE INDEX \"$owner\".\"UQ_EMAIL\"")

        val orders = i.ddl(obj("ORDERS"))
        assertContains(orders, "GENERATED ALWAYS AS"); assertContains(orders, "ON DELETE CASCADE")
        val before = i.details(obj("ORDERS"))
        DriverManager.getConnection(fx.ds.url, fx.ds.user, fx.password).use { c ->
            c.createStatement().use { st ->
                st.execute("drop table orders")
                orders.split(Regex(";\\s*(\\n|$)")).filter { it.isNotBlank() }.forEach { st.execute(it) }
            }
        }
        val after = i.details(obj("ORDERS"))
        assertEquals(before.columns.map { it.name to it.typeName }, after.columns.map { it.name to it.typeName })
        assertEquals(before.primaryKey, after.primaryKey); assertEquals(before.foreignKeys.map { it.name }, after.foreignKeys.map { it.name })
        assertEquals(before.indexes.map { it.name }.toSet(), after.indexes.map { it.name }.toSet())
    }

