    // --- typed values -------------------------------------------------------------------------

    private fun read(s: Session, sql: String): StatementResult.Rows = s.runScript(listOf(sql)).single() as StatementResult.Rows
    private fun stored(sql: String): List<List<Any?>> = DriverManager.getConnection(fx.ds.url, fx.ds.user, fx.password).use { c ->
        val rs = c.createStatement().executeQuery(sql); val n = rs.metaData.columnCount
        buildList { while (rs.next()) add(List(n) { rs.getString(it + 1) }) }
    }

    private fun send(s: Session, table: String, pk: List<String>, updates: (List<List<Any?>>) -> List<RowEdit> = { emptyList() },
                     inserts: List<Map<String, CellValue>> = emptyList(), deletes: List<Int> = emptyList()) {
        val r = read(s, "select * from ${OracleDialect.qualified(obj(table))} order by 1"); val rows = r.cursor.fetch(100); r.cursor.close()
        s.execute(buildDml(OracleDialect, DbKind.ORACLE, obj(table), r.columns, pk, updates(rows), inserts, deletes.map { rows[it] })).getOrThrow()
    }

    @Test fun theDriverReportsTypesAndNormalisesTheValuesItReturns() = Session(fx.ds, fx.password).use { s ->
        DriverManager.getConnection(fx.ds.url, fx.ds.user, fx.password).use { c ->
            c.createStatement().apply {
                execute("delete from ev")
                execute("insert into ev values (1, date '2026-01-31' + 10/24 + 20/1440 + 30/86400, timestamp '2026-01-31 10:20:30.5', timestamp '2026-01-31 10:20:30 +01:00', timestamp '2026-01-31 10:20:30', 'a long text', 'ñandú')")
            }
        }
        val r = read(s, "select * from ev"); val row = r.cursor.fetch(1).single()
        val types = r.columns.map { it.typeName }
        assertEquals(listOf("NUMBER", "DATE"), types.take(2), types.toString())
        assertTrue(types[3].contains("TIMESTAMP"), types.toString())
        assertEquals("a long text", row[5])                                  // a CLOB arrives as text
        assertIs<java.time.OffsetDateTime>(row[3])                           // and a TIMESTAMP WITH TIME ZONE as a standard value
        assertEquals(java.time.OffsetDateTime.parse("2026-01-31T10:20:30+01:00").toInstant(), (row[3] as java.time.OffsetDateTime).toInstant())
        assertEquals("ñandú", row[6])
        r.cursor.close()
    }

    @Test fun typedValuesRoundTripWithoutDependingOnTheSessionLanguage() = Session(fx.ds, fx.password).use { s ->
        DriverManager.getConnection(fx.ds.url, fx.ds.user, fx.password).use { it.createStatement().execute("delete from ev") }
        val t = { x: String -> CellValue.Text(x) }
        send(s, "EV", listOf("ID"), inserts = listOf(mapOf(
            "ID" to t("1"), "D" to t("2026-01-05 10:20:30"), "TS" to t("2026-01-05 10:20:30"), "TSTZ" to t("2026-01-05 10:20:30+05:30"),
            "TSLTZ" to t("2026-01-05 10:20:30"), "BIG" to t("x".repeat(5000)), "NAME" to t("ñandú"),
        )))
        val r = stored("select to_char(d, 'YYYY-MM-DD HH24:MI:SS'), to_char(ts, 'YYYY-MM-DD HH24:MI:SS'), to_char(tstz, 'YYYY-MM-DD HH24:MI:SS TZH:TZM'), length(big), name from ev").single()
        assertEquals(listOf<Any?>("2026-01-05 10:20:30", "2026-01-05 10:20:30", "2026-01-05 10:20:30 +05:30", "5000", "ñandú"), r)
        send(s, "EV", listOf("ID"), updates = { rows -> listOf(RowEdit(rows[0], mapOf("D" to t("2027-12-24"), "TSTZ" to CellValue.Null))) })
        assertEquals(listOf<Any?>("2027-12-24 00:00:00", null), stored("select to_char(d, 'YYYY-MM-DD HH24:MI:SS'), tstz from ev").single())
        send(s, "EV", listOf("ID"), deletes = listOf(0))
        assertEquals(emptyList(), stored("select 1 from ev"))
    }

    @Test fun anInsertWithNothingUsesTheDefaults() = Session(fx.ds, fx.password).use { s ->
        DriverManager.getConnection(fx.ds.url, fx.ds.user, fx.password).use { it.createStatement().execute("delete from auto") }
        send(s, "AUTO", listOf("ID"), inserts = listOf(mapOf("ID" to CellValue.Default, "N" to CellValue.Default)))
        assertEquals(listOf<Any?>("7"), stored("select n from auto").single())
    }

    @Test fun manualTransactionsWorkOnOracle() = Session(fx.ds.copy(manualTx = true), fx.password).use { s ->
        DriverManager.getConnection(fx.ds.url, fx.ds.user, fx.password).use { it.createStatement().execute("delete from auto") }
        s.runScript(listOf("insert into auto(n) values (1)"))
        assertTrue(s.pending); assertEquals(emptyList(), stored("select n from auto"))
        s.commit(); assertEquals(listOf<List<Any?>>(listOf("1")), stored("select n from auto"))
    }

